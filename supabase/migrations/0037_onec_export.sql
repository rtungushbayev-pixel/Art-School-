-- Выгрузка оплат в 1С:Бухгалтерию.
--
-- У ученика в списке школы появляется «код в 1С» (номер договора или код
-- контрагента), его задаёт администратор. У каждой оплаты — сквозной номер
-- export_id: 1С забирает новые оплаты «после номера N» через функцию
-- onec-payments (по секретному ключу) и создаёт поступление на ребёнка.
--
-- Выполнять после 0036.

alter table public.school_roster add column if not exists onec_code text
  check (onec_code is null or length(trim(onec_code)) between 1 and 50);

create unique index if not exists school_roster_onec_code_uidx
  on public.school_roster (onec_code) where onec_code is not null;

-- Код в 1С и dealId Битрикса меняет только администратор.
create or replace function public.protect_roster_external_ids()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.onec_code := old.onec_code;
    new.bitrix_deal_id := old.bitrix_deal_id;
  end if;
  new.onec_code := nullif(trim(coalesce(new.onec_code, '')), '');
  return new;
end;
$$;

drop trigger if exists school_roster_protect_external_ids on public.school_roster;
create trigger school_roster_protect_external_ids
  before update on public.school_roster
  for each row execute function public.protect_roster_external_ids();

-- Сквозной номер записи для выгрузки.
alter table public.billing_entries add column if not exists export_id bigint generated by default as identity;
create unique index if not exists billing_entries_export_id_uidx on public.billing_entries (export_id);
