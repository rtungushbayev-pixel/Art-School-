// Очки: 1 — за участие в прошедшем конкурсе или выставке школы,
// 2 — за достижение, подтверждённое школой. Считает база (0055).
export const POWER_THRESHOLDS: Record<Exclude<HeroPower, 0>, number> = { 1: 1, 2: 3, 3: 6, 4: 10 };

export function powerForPoints(points: number): HeroPower {
  if (points >= POWER_THRESHOLDS[4]) return 4;
  if (points >= POWER_THRESHOLDS[3]) return 3;
  if (points >= POWER_THRESHOLDS[2]) return 2;
  if (points >= POWER_THRESHOLDS[1]) return 1;
  return 0;
}

