export async function fetchHeroPoints(studentId: string): Promise<number> {
  const { data, error } = await supabase.rpc('hero_power_points', { p_student_id: studentId });
  if (error) throw error;
  return Number(data ?? 0);
}

export async function saveHero(userId: string, heroId: HeroId): Promise<void> {
  const { error } = await supabase.from('profiles').update({ hero_id: heroId }).eq('id', userId);
  if (error) throw error;
}
